void ConsoleUI::ClearScreen()
{
	// 콘솔 핸들 가져오기
	HANDLE hConsole = GetStdHandle(STD_OUTPUT_HANDLE);
	// 화면을 지우고 커서를 (0, 0)으로 이동
	COORD coord = { 0, 0 };
	DWORD written;
	CONSOLE_SCREEN_BUFFER_INFO csbi;
	GetConsoleScreenBufferInfo(hConsole, &csbi);
	DWORD size = csbi.dwSize.X * csbi.dwSize.Y;
	FillConsoleOutputCharacter(hConsole, ' ', size, coord, &written);
	FillConsoleOutputAttribute(hConsole, csbi.wAttributes, size, coord, &written);
	SetConsoleCursorPosition(hConsole, coord);
}

void ConsoleUI::MoveCursor(int x, int y)
{
	// 콘솔 핸들 가져오기
	HANDLE hConsole = GetStdHandle(STD_OUTPUT_HANDLE);
	// 커서 위치 설정
	COORD coord = { static_cast<SHORT>(x), static_cast<SHORT>(y) };
	SetConsoleCursorPosition(hConsole, coord);
}

void ConsoleUI::PrintStartScreen()
{
    int frame = 0;

    // 키보드 입력이 들어올 때까지 계속 파도 애니메이션을 재생
    while (!_kbhit())
    {

        MoveCursor(0, 0);

        cout.flush(); // 화면 클리어



        // 2. 파도 물결 모양 아스키 아트 (프레임별 애니메이션)
        if (frame % 2 == 0)
        {
            system("cls");

            // 1. 상단 구분선 (청록색)
            cout << CYAN;
            PrintLine();
            cout << RESET;


            // [프레임 A]
            cout << CYAN << BOLD;
            cout << R"(
                .  :%=..                 .--..                 . ..
            .@@@@@*@@@@-           :@@@@@@@@@@           .@@@@@@@@@@.
            @@@-.@@. ..@@=        .@@@ =@+.  @@@        .@@@. @@.. %@@
        .@@# .@@    .@@        @@@  @@     @@.       .@@. @@*    =@@
        @@@ ..@@@             .@@..@ @@              @@@ @ @@
    .@@. .@%-@@.           @@@  %@.@@*           -@@. .@ @@@
    :@@@ . .@@.#@@@.      .@@@.   #@@.@@@.      .@@@:.  .@@.@@@*
@@      ..@@@.@@@@@@@@@@-      .@@@.*@@@@@@@@@@.      :@@@.@@@@@@@@@@@.
                .@@@@@@@@@.           .@@@@@@@@@*            @@@@@@@@@@

                )" << endl;

        }
        else
        {
            system("cls");

            // 1. 상단 구분선 (청록색)
            cout << CYAN;
            PrintLine();
            cout << RESET;

            // [프레임 B - 좌우 한 칸 이동 및 모양 변화]
            cout << BLUE << BOLD;
            cout << R"(
                 .  :%=..                 .--..
              .@@@@@*@@@@-           :@@@@@@@@@@           .@@@@@
             @@@-.@@. ..@@=        .@@@ =@+.  @@@        .@@@. @@
           .@@# .@@    .@@        @@@  @@     @@.       .@@. @@*
          @@@ ..@@@             .@@..@ @@              @@@ @ @@
         @@. .@%-@@.           @@@  %@.@@*           -@@. .@ @@@
      .@@.#@@@.              .@@@.   #@@.@@@.      .@@@:.  .@@.@@@*
    .@@@            @@@.@@@@@@@@@@-      .@@@.*@@@@@@@@@@.      
:@@@.@@@@@@@@@@
    @@@@@    @@@@@@@@@.           .@@@@@@@@@*            @@@@@@@@@@
                )" << endl;
        }

        // 3. 타이틀 로고 ASCII ART : 파도 (중앙 정렬)
        cout << CYAN << BOLD;

        cout << R"(
                      ____   _    ____   ___  
                     |  _ \ / \  |  _ \ / _ \ 
                     | |_) / _ \ | | | | | | |
                     |  __/ ___ \| |_| | |_| |
                     |_| /_/   \_\____/ \___/ 
                
                )" << endl;

        cout << RESET;

        // 구분선
        cout << CYAN;
        PrintLine();
        cout << RESET;

        // 4. 게임 서사 문구
        cout << MAGENTA << BOLD << "\n           \"우리는 서로의 천국이자, 가장 잔인한 지옥이었다.\"\n\n" << RESET;

        // 구분선
        cout << CYAN;
        PrintLine();
        cout << RESET;

        // 5. 시작 안내 문구
        cout << WHITE << BOLD << "                   >> 아무 키나 누르면 시작됩니다 <<\n" << RESET;

        // 하단 구분선
        cout << CYAN;
        PrintLine();
        cout << RESET;

        // 프레임 증가 및 대기 (300ms 간격으로 파도가 출렁거림)
        frame++;
        this_thread::sleep_for(chrono::milliseconds(300));
    }

    // 버퍼에 남아있는 키 입력 소모 (다음 화면에 영향 없도록 버퍼 삭제)
    _getch();
}
